"""Small CPU-only learned candidate detector for faint whiteboard ink.

The model is deliberately an optional research layer.  It returns a probability
map and never changes the confirmed board by itself.  Weights are generated by
the reproducible experiment under ``experiments/weak-ink``.
"""
from __future__ import annotations

from pathlib import Path
import cv2
import numpy as np


FEATURES = 8
V2_FEATURES = 13


def _features(bgr: np.ndarray) -> np.ndarray:
    if bgr.dtype != np.uint8 or bgr.ndim != 3 or bgr.shape[2] != 3:
        raise ValueError("expected uint8 BGR image")
    smooth = cv2.GaussianBlur(bgr, (3, 3), 0.7)
    gray = cv2.cvtColor(smooth, cv2.COLOR_BGR2GRAY).astype(np.float32) / 255.0
    paper = cv2.morphologyEx(gray, cv2.MORPH_CLOSE, np.ones(( nine := 9, nine), np.uint8))
    detail = np.clip(paper - gray, 0, 1)
    gx = cv2.Sobel(gray, cv2.CV_32F, 1, 0, ksize=3)
    gy = cv2.Sobel(gray, cv2.CV_32F, 0, 1, ksize=3)
    edge = np.sqrt(gx * gx + gy * gy)
    # Chroma helps preserve faint red/blue marker strokes.
    ycrcb = cv2.cvtColor(smooth, cv2.COLOR_BGR2YCrCb).astype(np.float32)
    chroma = np.sqrt((ycrcb[..., 1] - 128) ** 2 + (ycrcb[..., 2] - 128) ** 2) / 128.0
    local = cv2.GaussianBlur(gray, (0, 0), 5)
    contrast = np.abs(gray - local)
    # Directional support rejects isolated dirt and JPEG blocks.
    hline = np.abs(cv2.Sobel(gray, cv2.CV_32F, 0, 1, ksize=3))
    vline = np.abs(cv2.Sobel(gray, cv2.CV_32F, 1, 0, ksize=3))
    return np.stack([gray, detail, edge, chroma, contrast, hline, vline,
                     np.ones_like(gray)], axis=-1).astype(np.float32)


def _features_v2(bgr: np.ndarray) -> np.ndarray:
    """Context features for the V2 candidate model.

    Each pixel sees directional and multi-scale neighborhood evidence. This is
    still a tiny CPU model, but unlike V1 it can distinguish a continuous faint
    stroke from an isolated paper texture or JPEG block.
    """
    if bgr.dtype != np.uint8 or bgr.ndim != 3 or bgr.shape[2] != 3:
        raise ValueError("expected uint8 BGR image")
    smooth = cv2.GaussianBlur(bgr, (3, 3), .7)
    gray = cv2.cvtColor(smooth, cv2.COLOR_BGR2GRAY).astype(np.float32) / 255.0
    paper = cv2.morphologyEx(gray, cv2.MORPH_CLOSE, np.ones((11, 11), np.uint8))
    detail = np.clip(paper - gray, 0, 1)
    local = cv2.GaussianBlur(gray, (0, 0), 5)
    contrast = np.abs(gray - local)
    gx = cv2.Sobel(gray, cv2.CV_32F, 1, 0, ksize=3)
    gy = cv2.Sobel(gray, cv2.CV_32F, 0, 1, ksize=3)
    edge = np.sqrt(gx * gx + gy * gy)
    ycc = cv2.cvtColor(smooth, cv2.COLOR_BGR2YCrCb).astype(np.float32)
    chroma_r = np.abs(ycc[..., 1] - 128) / 128
    chroma_b = np.abs(ycc[..., 2] - 128) / 128
    # Directional line support uses normalized black/colour evidence.
    signal = np.clip(detail + .45 * np.sqrt(chroma_r * chroma_r + chroma_b * chroma_b), 0, 1)
    kernels = []
    for size in (5, 9):
        kernels.extend([cv2.getStructuringElement(cv2.MORPH_RECT, (size, 1)),
                        cv2.getStructuringElement(cv2.MORPH_RECT, (1, size))])
    directional = [cv2.morphologyEx(signal, cv2.MORPH_CLOSE, k) - signal for k in kernels]
    # Local variance rejects broad saturated plateaus and smooth paper shading.
    mean = cv2.GaussianBlur(gray, (0, 0), 2)
    mean2 = cv2.GaussianBlur(gray * gray, (0, 0), 2)
    variance = np.maximum(mean2 - mean * mean, 0)
    border = np.minimum.reduce([np.indices(gray.shape)[0], np.indices(gray.shape)[1],
                                gray.shape[0] - 1 - np.indices(gray.shape)[0],
                                gray.shape[1] - 1 - np.indices(gray.shape)[1]]).astype(np.float32)
    border = np.exp(-border / max(2, min(gray.shape) * .04))
    return np.stack([gray, detail, contrast, edge, chroma_r, chroma_b,
                     *directional, variance, border, np.ones_like(gray)], axis=-1).astype(np.float32)


class WeakInkModel:
    def __init__(self, weights: dict[str, np.ndarray]):
        self.w1 = np.asarray(weights["w1"], np.float32)
        self.b1 = np.asarray(weights["b1"], np.float32)
        self.w2 = np.asarray(weights["w2"], np.float32)
        self.b2 = np.asarray(weights["b2"], np.float32)
        if self.w1.shape[0] != FEATURES or self.w2.shape[0] != self.w1.shape[1]:
            raise ValueError("invalid weak ink weights")

    def predict_proba(self, bgr: np.ndarray, known: np.ndarray | None = None) -> np.ndarray:
        feat = _features(bgr)
        flat = feat.reshape(-1, FEATURES)
        hidden = np.tanh(flat @ self.w1 + self.b1)
        logits = hidden @ self.w2 + self.b2
        probability = (1.0 / (1.0 + np.exp(-np.clip(logits, -30, 30))))
        result = probability.reshape(bgr.shape[:2]).astype(np.float32)
        if known is not None:
            if known.shape != result.shape:
                raise ValueError("known mask shape differs from image")
            # Never infer a mark in a region that the board estimator has not
            # observed reliably. The caller may still inspect the raw map by
            # omitting ``known`` during offline analysis.
            result = np.where(known == 255, result, 0.0)
        return result


class WeakInkV2Model(WeakInkModel):
    """V2 model using multi-scale neighborhood features."""
    def __init__(self, weights: dict[str, np.ndarray]):
        self.w1 = np.asarray(weights["w1"], np.float32)
        self.b1 = np.asarray(weights["b1"], np.float32)
        self.w2 = np.asarray(weights["w2"], np.float32)
        self.b2 = np.asarray(weights["b2"], np.float32)
        if self.w1.shape[0] != V2_FEATURES or self.w2.shape[0] != self.w1.shape[1]:
            raise ValueError("invalid weak ink V2 weights")

    def predict_proba(self, bgr: np.ndarray, known: np.ndarray | None = None) -> np.ndarray:
        feat = _features_v2(bgr)
        flat = feat.reshape(-1, V2_FEATURES)
        hidden = np.tanh(flat @ self.w1 + self.b1)
        logits = hidden @ self.w2 + self.b2
        result = (1.0 / (1.0 + np.exp(-np.clip(logits[:, 0], -30, 30)))).reshape(bgr.shape[:2]).astype(np.float32)
        if known is not None:
            if known.shape != result.shape:
                raise ValueError("known mask shape differs from image")
            result = np.where(known == 255, result, 0.0)
        return result


def load_model(path: str | Path) -> WeakInkModel:
    with np.load(path) as data:
        weights = {key: data[key] for key in ("w1", "b1", "w2", "b2")}
        if weights["w1"].shape[0] == V2_FEATURES:
            return WeakInkV2Model(weights)
        return WeakInkModel(weights)


def candidate_mask(model: WeakInkModel, bgr: np.ndarray, threshold: float = 0.72,
                   known: np.ndarray | None = None) -> np.ndarray:
    """Return a conservative uint8 candidate mask, never a confirmed state."""
    if not 0 < threshold < 1:
        raise ValueError("threshold must be between 0 and 1")
    probability = model.predict_proba(bgr, known)
    mask = (probability >= threshold).astype(np.uint8) * 255
    # Do not morphologically open the mask here. A 1-pixel faint stroke is a
    # valid candidate and opening it would erase exactly the detail this layer
    # is intended to recover. Spatial cleanup belongs to the geometry stage.
    return mask
